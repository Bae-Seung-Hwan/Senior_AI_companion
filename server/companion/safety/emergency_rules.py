"""응급 감지 1단계: 규칙 (#26). 구조는 사기 감지(rules.py)와 같다.

1. **문지기 (is_candidate)**: 몸·위험 낱말이 하나도 없으면 LLM을 부르지 않는다.
   응급은 놓치면 안 되므로 사기보다 더 넓게 잡는다. "무릎이 좀 아파", "더워 죽겠어"처럼 응급이 아닌 말도
   통과하지만, 그건 LLM이 거른다. 테스트 문장 세트(samples/emergency_cases.json)의 응급 문장은 모두
   통과해야 한다 (tests/test_safety.py)
2. **안전망 (strong_signal)**: LLM 호출이 실패했을 때만 쓴다. 지금 일어나는 분명한 위급 표현만 본다.
   "배불러 죽겠어" 같은 관용 표현과 "어제 넘어졌었는데" 같은 지난 일은 걸리지 않게 좁게 잡는다
"""

from __future__ import annotations

import re

from .models import ACUTE

BODY_DANGER_WORDS = (
    # 넘어짐·쓰러짐·다침
    "넘어", "쓰러", "미끄러", "자빠", "낙상", "굴러", "꺾였", "꺾여", "다쳤", "다쳐", "베였", "베여", "데었",
    "화상", "피가", "피 나", "부러", "삐었", "못 일어나",
    "일어날 수가 없", "일어나질 못", "움직일 수가 없", "꼼짝",
    # 가슴·숨
    "가슴", "숨이", "숨을", "숨쉬", "숨 쉬", "숨차", "호흡",
    # 말·마비·의식
    "어눌", "말이 안 나", "말이 잘 안", "혀가 꼬", "마비", "저려", "저리", "감각이 없", "힘이 안 들어", "힘이 하나도",
    "의식", "정신을 잃", "정신이 없", "기절", "까무러", "눈앞이 캄캄", "어지러", "어질어질", "핑 돌",
    # 아픔·몸 상태 (넓게)
    "아파", "아프", "아픈", "통증", "토했", "토할", "구토", "식은땀", "열이", "경련",
    # 목에 걸림
    "목에 걸", "목이 막", "사레",
    # 집 안 위험
    "불이", "불났", "불 났", "연기", "타는 냄새", "가스 냄새", "가스가 새",
    # 다른 사람
    "남편이", "아내가", "할아버지가", "할머니가", "영감이", "마누라가",
    # 도움 요청·마음
    "살려", "도와줘", "도와 줘", "119", "구급차", "응급", "죽고 싶", "죽을 것", "죽겠", "살기 싫", "살고 싶지",
    "끝내고 싶", "사라지고 싶", "없어지고 싶", "없어지는 게", "사라지는 게", "그만 살", "살아서 뭐", "살 이유",
)

# 지금 일어나는 분명한 위급 표현 (안전망). 관용 표현("더워 죽겠어", "배불러 죽겠어")은 넣지 않는다
_ACUTE = (
    ("fall", re.compile(r"(넘어졌|넘어져서|쓰러졌|미끄러졌).*(못 일어나|일어날 수가 없|일어나질 못|움직일 수가 없)"
                        r"|못 일어나겠|일어날 수가 없어")),
    ("chest", re.compile(r"가슴이 (너무|많이|찢어질 듯|터질 듯|조여|짓눌)|가슴을 쥐어짜")),
    ("breathing", re.compile(r"숨이 (안 쉬|막혀|막힐|턱턱|가빠서 못)|숨을 (못 쉬|쉴 수가 없)")),
    ("speech_or_weakness", re.compile(r"말이 (안 나와|어눌)|혀가 꼬|(한쪽|반쪽|팔|다리)(이|가)? ?(마비|안 움직|힘이 안)")),
    ("fainting", re.compile(r"정신을 잃|기절|까무러|눈앞이 캄캄")),
    ("bleeding_injury", re.compile(r"피가 (안 멈|많이|철철|계속)")),
    ("choking", re.compile(r"목에 (뭐가|무언가|떡이|음식이)? ?걸려서|숨이 막혀")),
    ("fire_gas", re.compile(r"불이 났|불났어|불이야|연기가 (나|차)|가스 (냄새|가 새)")),
    ("other_person", re.compile(r"(남편|아내|영감|마누라|할아버지|할머니)(이|가) (쓰러|숨을 안|의식이 없|말을 안)")),
    ("self_harm", re.compile(r"죽고 싶|살기 싫|살고 싶지 않|끝내고 싶|그만 살고")),
    ("other", re.compile(r"살려 ?줘|구급차 (좀 )?불러|119 (좀 )?불러")),
)
# 지난 일. "어제부터 아파"는 지금도 계속되는 것이라 지난 일이 아니다. "자기 전에" 같은 말에 걸리지 않게 "전에"는 넣지 않는다
_PAST = re.compile(r"어제(?!부터)|그저께(?!부터)|그제(?!부터)|지난주(?!부터)|지난번|지난달|예전에|옛날에|"
                   r"이제 (다 )?괜찮|지금은 (다 )?괜찮|다 나았")


def is_candidate(text: str, recent: tuple[str, ...] | list[str] = ()) -> bool:
    """LLM에게 물어볼 만한 발화인지 (문지기). recent는 쓰지 않는다 (응급은 지금 한 말로 판단)."""
    return any(w in text for w in BODY_DANGER_WORDS)


def strong_signal(text: str, recent: tuple[str, ...] | list[str] = ()) -> tuple[str, str] | None:
    """LLM 없이도 알릴 만큼 분명한 응급이면 (유형, 단계), 아니면 None. LLM이 실패했을 때만 쓴다."""
    # "죽고 싶다"는 다른 말과 섞여도, 지난 일처럼 말해도 먼저 본다
    if dict(_ACUTE)["self_harm"].search(text):
        return "self_harm", ACUTE
    if _PAST.search(text):
        return None  # 지난 일 ("어제 넘어졌었는데 이제 괜찮아")
    for category, pattern in _ACUTE:
        if pattern.search(text):
            return category, ACUTE
    return None
